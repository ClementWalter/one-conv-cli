"""Oh My Pi: a one-conv extension inside each omp process registers the session and drains its inbox.

omp has no external input channel into a running TUI, so delivery is a file dropped in
`<live>/inbox/omp/<session id>/`; the extension injects it with `pi.sendUserMessage`.
"""

import json
import os
import uuid
from pathlib import Path

from .model import LiveSession, is_session_id, live_home, pid_alive


def omp_home() -> Path:
    return Path(os.environ.get("OMP_HOME", str(Path.home() / ".omp")))


def extension_path() -> Path:
    return omp_home() / "agent" / "extensions" / "one-conv-live.ts"


def _registry() -> Path:
    return live_home() / "omp"


def inbox(session_id: str) -> Path:
    if not is_session_id(session_id):
        raise ValueError(f"not an omp session id: {session_id!r}")
    return live_home() / "inbox" / "omp" / session_id


def _session(data: dict) -> LiveSession:
    return LiveSession("omp", data["sessionId"], data.get("cwd", ""), data.get("title", ""),
                       data.get("status", ""), data.get("pid"), "extension inbox",
                       str(inbox(data["sessionId"])))


def _records() -> list[dict]:
    rows = []
    for path in sorted(_registry().glob("*.json")):
        try:
            data = json.loads(path.read_text())
        except (OSError, ValueError):
            continue
        if isinstance(data, dict) and is_session_id(str(data.get("sessionId") or "")):
            rows.append(data)
    return rows


def list_sessions() -> list[LiveSession]:
    return [_session(data) for data in _records() if pid_alive(data.get("pid"))]


def session_for_pid(pid: int) -> LiveSession | None:
    return next((_session(data) for data in _records() if data.get("pid") == pid), None)


def deliver(session: LiveSession, text: str) -> str:
    target = inbox(session.id)
    target.mkdir(parents=True, exist_ok=True)
    name = f"{uuid.uuid4().hex}.json"
    # The extension only picks up `*.json`, so the rename publishes a complete file.
    partial = target / f".{name}.tmp"
    partial.write_text(json.dumps({"text": text}))
    partial.rename(target / name)
    return "delivered"


EXTENSION = r"""// one-conv live relay: registers this omp session and injects messages from its inbox.
// Generated by `one-conv live install`; reinstalling overwrites it.
import * as fs from "node:fs";
import * as path from "node:path";
import { execFile } from "node:child_process";
import type { ExtensionAPI } from "@oh-my-pi/pi-coding-agent";

const LIVE = __LIVE_DIR__;
const LAUNCHER: string[] = __LAUNCHER__;

export default function (pi: ExtensionAPI) {
  const z = pi.zod;
  let current = "";

  const registryFile = (id: string) => path.join(LIVE, "omp", `${id}.json`);

  const register = (ctx: any) => {
    const id = ctx.sessionManager.getSessionId();
    if (!id) return;
    if (current && current !== id) fs.rmSync(registryFile(current), { force: true });
    current = id;
    let title = "";
    try { title = pi.getSessionName?.() ?? ""; } catch {}
    const row = { pid: process.pid, sessionId: id, cwd: ctx.cwd, title,
                  sessionFile: ctx.sessionManager.getSessionFile?.() ?? "",
                  status: ctx.isIdle() ? "idle" : "busy" };
    fs.mkdirSync(path.join(LIVE, "omp"), { recursive: true });
    const partial = `${registryFile(id)}.${process.pid}.tmp`;
    fs.writeFileSync(partial, JSON.stringify(row));
    fs.renameSync(partial, registryFile(id));
  };

  const drain = (ctx: any) => {
    const dir = path.join(LIVE, "inbox", "omp", current);
    if (!fs.existsSync(dir)) return;
    for (const name of fs.readdirSync(dir).filter((n) => n.endsWith(".json")).sort()) {
      const claimed = path.join(dir, `${name}.${process.pid}.claimed`);
      try { fs.renameSync(path.join(dir, name), claimed); } catch { continue; }
      let text = "";
      try { text = JSON.parse(fs.readFileSync(claimed, "utf8")).text ?? ""; } catch {}
      // A malformed file is dropped; throwing here would tear down the whole omp session.
      fs.rmSync(claimed, { force: true });
      if (!text) continue;
      if (ctx.isIdle()) pi.sendUserMessage(text);
      else pi.sendUserMessage(text, { deliverAs: "followUp" });
    }
  };

  pi.on("session_start", async (_event, ctx) => {
    register(ctx);
    ctx.setInterval(() => { register(ctx); drain(ctx); }, 1000);
  });

  pi.on("session_shutdown", async () => {
    if (current) fs.rmSync(registryFile(current), { force: true });
  });

  pi.registerTool({
    name: "one_conv_send",
    label: "one-conv send",
    description: "Send a message to another live agent session (address like claude:<id>, codex:<id>, omp:<id>). Run `one-conv live ls` to list them. Set fyi for acknowledgments, sign-offs and completion notices: they wait in the receiver's feed and expect no reply. Set noReply to push an awaited result or blocker that needs no answer. Never answer a message marked reply=\"none\".",
    parameters: z.object({ to: z.string(), message: z.string(), fyi: z.boolean().optional(),
                           noReply: z.boolean().optional() }),
    async execute(_id, params) {
      const flags = params.fyi ? ["--fyi"] : params.noReply ? ["--no-reply"] : [];
      const args = [...LAUNCHER.slice(1), "live", "send", "--yes", ...flags, "--from", `omp:${current}`, "--", params.to, params.message];
      const text: string = await new Promise((resolve) => {
        execFile(LAUNCHER[0], args, { timeout: 60000 }, (error, stdout, stderr) =>
          resolve(error ? `failed: ${stderr || error.message}` : stdout.trim()));
      });
      return { content: [{ type: "text", text }] };
    },
  });
}
"""


def render_extension(launcher: list[str]) -> str:
    return (EXTENSION.replace("__LIVE_DIR__", json.dumps(str(live_home())))
            .replace("__LAUNCHER__", json.dumps(launcher)))
